-- "shop" fixture, Oracle (unquoted names are stored uppercase).
CREATE SEQUENCE products_seq INCREMENT BY 1;
CREATE TABLE countries (code CHAR(2) PRIMARY KEY, name VARCHAR2(80) NOT NULL);
CREATE TABLE customers (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR2(120) NOT NULL UNIQUE,
  full_name VARCHAR2(100) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  notes CLOB);
CREATE TABLE products (
  id NUMBER(19) DEFAULT products_seq.NEXTVAL PRIMARY KEY,
  sku VARCHAR2(40) NOT NULL UNIQUE,
  name VARCHAR2(100) NOT NULL,
  price NUMBER(10,2) NOT NULL,
  country_code CHAR(2) REFERENCES countries (code));
CREATE TABLE orders (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id NUMBER(19) NOT NULL REFERENCES customers (id),
  ordered_on DATE NOT NULL,
  status VARCHAR2(20) DEFAULT 'NEW' NOT NULL);
CREATE TABLE order_items (
  order_id NUMBER(19) NOT NULL REFERENCES orders (id),
  line_no NUMBER(9) NOT NULL,
  product_id NUMBER(19) NOT NULL REFERENCES products (id),
  quantity NUMBER(9) NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (order_id, line_no));
CREATE TABLE tags (id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR2(40) NOT NULL UNIQUE);
CREATE TABLE product_tags (
  product_id NUMBER(19) NOT NULL REFERENCES products (id),
  tag_id NUMBER(19) NOT NULL REFERENCES tags (id),
  PRIMARY KEY (product_id, tag_id));
