-- "shop" fixture, Db2 LUW (no sequence defaults: keys use identity).
CREATE TABLE countries (code CHAR(2) NOT NULL PRIMARY KEY, name VARCHAR(80) NOT NULL);
CREATE TABLE customers (
  id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(120) NOT NULL UNIQUE,
  full_name VARCHAR(100) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT TIMESTAMP,
  notes CLOB(1M));
CREATE TABLE products (
  id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  country_code CHAR(2) REFERENCES countries (code));
CREATE TABLE orders (
  id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers (id),
  ordered_on DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'NEW');
CREATE TABLE order_items (
  order_id BIGINT NOT NULL REFERENCES orders (id),
  line_no INTEGER NOT NULL,
  product_id BIGINT NOT NULL REFERENCES products (id),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (order_id, line_no));
CREATE TABLE tags (id BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(40) NOT NULL UNIQUE);
CREATE TABLE product_tags (
  product_id BIGINT NOT NULL REFERENCES products (id),
  tag_id BIGINT NOT NULL REFERENCES tags (id),
  PRIMARY KEY (product_id, tag_id));
