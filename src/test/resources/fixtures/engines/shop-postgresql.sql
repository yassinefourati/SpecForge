-- "shop" fixture, PostgreSQL. The same model in every engine's DDL (EngineMatrixIT).
CREATE SEQUENCE products_seq INCREMENT BY 1;
CREATE TABLE countries (code CHAR(2) PRIMARY KEY, name VARCHAR(80) NOT NULL);
CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(120) NOT NULL UNIQUE,
  full_name VARCHAR(100) NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  notes TEXT);
CREATE TABLE products (
  id BIGINT DEFAULT nextval('products_seq') PRIMARY KEY,
  sku VARCHAR(40) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  price DECIMAL(10,2) NOT NULL,
  country_code CHAR(2) REFERENCES countries (code));
ALTER SEQUENCE products_seq OWNED BY products.id;
CREATE TABLE orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id BIGINT NOT NULL REFERENCES customers (id),
  ordered_on DATE NOT NULL,
  status VARCHAR(20) DEFAULT 'NEW' NOT NULL);
CREATE TABLE order_items (
  order_id BIGINT NOT NULL REFERENCES orders (id),
  line_no INTEGER NOT NULL,
  product_id BIGINT NOT NULL REFERENCES products (id),
  quantity INTEGER NOT NULL CHECK (quantity > 0),
  PRIMARY KEY (order_id, line_no));
CREATE TABLE tags (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, label VARCHAR(40) NOT NULL UNIQUE);
CREATE TABLE product_tags (
  product_id BIGINT NOT NULL REFERENCES products (id),
  tag_id BIGINT NOT NULL REFERENCES tags (id),
  PRIMARY KEY (product_id, tag_id));
