-- Prior-art regression fixture (docs/prompts/phase-database-first.md §18.3).
-- Rebuilt from the entities the owner's Hibernate Tools generator produced from this schema
-- (D:\Workspace\workspace\Java\reverse_engineering), with the column types those entities lost restored:
-- error_logs.details is jsonb, timestamps are timestamptz. Keys deliberately mix identity columns,
-- bigserial and an explicit sequence so ID detection (MAP-7) is exercised.

CREATE SCHEMA administration;

CREATE TABLE administration.users (
    user_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name   varchar(100) NOT NULL,
    last_name    varchar(100) NOT NULL,
    email        varchar(255) NOT NULL UNIQUE,
    username     varchar(100) NOT NULL UNIQUE,
    password     varchar(255) NOT NULL,
    status       varchar(20)  NOT NULL,
    created_date timestamptz  NOT NULL DEFAULT now(),
    updated_date timestamptz  NOT NULL DEFAULT now()
);
COMMENT ON TABLE administration.users IS 'Application users';

CREATE TABLE administration.roles (
    role_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name    varchar(100) NOT NULL UNIQUE,
    description  text,
    created_date timestamptz  NOT NULL DEFAULT now(),
    updated_date timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE administration.permissions (
    permission_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    permission_name varchar(100) NOT NULL UNIQUE,
    description     text,
    created_date    timestamptz  NOT NULL DEFAULT now()
);

-- pure join table: two foreign keys forming the primary key
CREATE TABLE administration.role_permissions (
    role_id       bigint NOT NULL REFERENCES administration.roles (role_id),
    permission_id bigint NOT NULL REFERENCES administration.permissions (permission_id),
    PRIMARY KEY (role_id, permission_id)
);

-- composite key of two foreign keys plus its own column: an entity, not a pure join table
CREATE TABLE administration.user_roles (
    user_id       bigint      NOT NULL REFERENCES administration.users (user_id),
    role_id       bigint      NOT NULL REFERENCES administration.roles (role_id),
    assigned_date timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role_id)
);

-- a column named "timestamp" that must NOT become @Version (prior-art defect)
CREATE TABLE administration.audit_logs (
    audit_id  bigserial PRIMARY KEY,
    timestamp timestamptz NOT NULL DEFAULT now(),
    user_id   bigint      NOT NULL REFERENCES administration.users (user_id),
    action    varchar(50) NOT NULL,
    details   text
);

CREATE TABLE administration.notifications (
    notification_id bigserial PRIMARY KEY,
    timestamp       timestamptz NOT NULL DEFAULT now(),
    user_id         bigint      NOT NULL REFERENCES administration.users (user_id),
    message         text        NOT NULL,
    read_status     boolean     NOT NULL DEFAULT false
);

-- explicit sequence (increment 1): allocationSize must be 1, not Hibernate's default 50
CREATE SEQUENCE administration.error_logs_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE administration.error_logs (
    error_id        bigint      PRIMARY KEY DEFAULT nextval('administration.error_logs_seq'),
    user_id         bigint      REFERENCES administration.users (user_id),
    error_message   text        NOT NULL,
    stack_trace     text,
    error_timestamp timestamptz NOT NULL DEFAULT now(),
    severity        varchar(50) NOT NULL,
    operation_name  text,
    details         jsonb
);
ALTER SEQUENCE administration.error_logs_seq OWNED BY administration.error_logs.error_id;

CREATE TABLE administration.support_tickets (
    ticket_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint       NOT NULL REFERENCES administration.users (user_id),
    subject      text         NOT NULL,
    description  text         NOT NULL,
    status       varchar(20)  NOT NULL,
    created_date timestamptz  NOT NULL DEFAULT now(),
    updated_date timestamptz  NOT NULL DEFAULT now()
);

-- string primary key: an assigned ID
CREATE TABLE administration.configurations (
    config_key   varchar(100) PRIMARY KEY,
    config_value text         NOT NULL,
    description  text,
    created_date timestamptz  NOT NULL DEFAULT now()
);
