                auth.requestMatchers(HttpMethod.GET, "/customers").authenticated();
                auth.requestMatchers(HttpMethod.GET, "/customers/{id}").authenticated();
                auth.requestMatchers(HttpMethod.PUT, "/customers/{id}").authenticated();
                auth.requestMatchers(HttpMethod.PATCH, "/customers/{id}").authenticated();
