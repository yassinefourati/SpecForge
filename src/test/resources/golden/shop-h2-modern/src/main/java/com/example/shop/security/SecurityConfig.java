                auth.requestMatchers(HttpMethod.GET, "/countries/{id}").authenticated();
                auth.requestMatchers(HttpMethod.PUT, "/countries/{id}").authenticated();
                auth.requestMatchers(HttpMethod.PATCH, "/countries/{id}").authenticated();
