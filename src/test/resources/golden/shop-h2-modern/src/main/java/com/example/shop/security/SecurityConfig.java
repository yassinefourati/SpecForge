                auth.requestMatchers(HttpMethod.POST, "/order-items").authenticated();
                auth.requestMatchers(HttpMethod.GET, "/order-items/{orderId}/{lineNo}").authenticated();
                auth.requestMatchers(HttpMethod.PUT, "/order-items/{orderId}/{lineNo}").authenticated();
                auth.requestMatchers(HttpMethod.PATCH, "/order-items/{orderId}/{lineNo}").authenticated();
                auth.requestMatchers(HttpMethod.DELETE, "/order-items/{orderId}/{lineNo}").authenticated();
                auth.requestMatchers(HttpMethod.GET, "/products").authenticated();
                auth.requestMatchers(HttpMethod.POST, "/products").authenticated();
                auth.requestMatchers(HttpMethod.GET, "/products/{id}").authenticated();
                auth.requestMatchers(HttpMethod.PUT, "/products/{id}").authenticated();
                auth.requestMatchers(HttpMethod.PATCH, "/products/{id}").authenticated();
                auth.requestMatchers(HttpMethod.DELETE, "/products/{id}").authenticated();
                auth.requestMatchers(HttpMethod.GET, "/tags").authenticated();
