package com.example.api.security;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.http.HttpMethod;
import org.springframework.http.HttpStatus;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.config.annotation.web.configuration.EnableWebSecurity;
import org.springframework.security.config.http.SessionCreationPolicy;
import org.springframework.security.web.SecurityFilterChain;
import org.springframework.security.web.authentication.HttpStatusEntryPoint;
import org.springframework.security.web.authentication.UsernamePasswordAuthenticationFilter;

/**
 * Spring Security configuration generated from the security schemes of "Pet Store".
 *
 * Declared schemes:
 *  - apiKey: APIKEY (X-API-KEY in header)
 *  - oauth: OAUTH2 (flows: clientCredentials, token URL: https://auth.example.com/token)
 *
 * Proxy mode, forwarded credentials: requests to protected endpoints must carry a credential, which the upstream
 * API validates (scopes included). Nothing is validated locally.
 *
 * Access rules style: MATCHERS. Scope authorities use the prefix "SCOPE_".
 *
 * Generated by SpecForge from "Pet Store" (1.0.0). Safe to edit.
 */
@Configuration
@EnableWebSecurity
public class SecurityConfig {

    @Bean
    public SecurityFilterChain securityFilterChain(HttpSecurity http,
            @Value("${app.upstream.forward-credentials:}") String forwardCredentials) throws Exception {
        http
            .csrf(csrf -> csrf.disable())
            .sessionManagement(session -> session.sessionCreationPolicy(SessionCreationPolicy.STATELESS))
            .authorizeHttpRequests(auth -> {
                // one statement per rule: a single chained expression overflows javac's stack on large APIs
                auth.requestMatchers(HttpMethod.GET, "/v1/pets").permitAll();
                auth.requestMatchers(HttpMethod.POST, "/v1/pets").authenticated();
                auth.requestMatchers(HttpMethod.GET, "/v1/pets/{petId}").permitAll();
                auth.requestMatchers(HttpMethod.DELETE, "/v1/pets/{petId}").authenticated();
                auth.anyRequest().authenticated();
            });
        // callers' credentials are validated by the upstream API; here a request only needs to carry one
        http.addFilterBefore(new ForwardedCredentialFilter(forwardCredentials), UsernamePasswordAuthenticationFilter.class);
        http.exceptionHandling(ex -> ex.authenticationEntryPoint(new HttpStatusEntryPoint(HttpStatus.UNAUTHORIZED)));
        return http.build();
    }
}
