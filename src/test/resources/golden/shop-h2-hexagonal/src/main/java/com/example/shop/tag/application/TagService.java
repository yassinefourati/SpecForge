@Service
@Transactional
public class TagService implements TagUseCases {

    private final TagRepositoryPort repository;
    private final Validator validator;

    public TagService(TagRepositoryPort repository, Validator validator) {
        this.repository = repository;
        this.validator = validator;
    }

    @Override
    @Transactional(readOnly = true)
    public PageResult<TagResponse> list(Map<String, String> filters, PageQuery page) {
        return repository.findAll(filters, page).map(TagService::toResponse);
    }

    @Override
    @Transactional(readOnly = true)
    public TagResponse read(Long id) {
        return toResponse(find(id));
    }

    @Override
    public TagResponse create(TagRequest request) {
        Tag item = new Tag();
        apply(request, item);
        return toResponse(repository.create(item));
    }

    @Override
    public TagResponse update(Long id, TagRequest request) {
        Tag item = find(id);
        apply(request, item);
        return toResponse(repository.update(item));
    }

    @Override
    public TagResponse patch(Long id, Map<String, Object> changes) {
        Tag item = find(id);
        if (changes.containsKey("label")) {
            if (changes.get("label") == null) {
                throw new ResponseStatusException(HttpStatus.BAD_REQUEST, "label cannot be null");
            }
            item.setLabel(ValueConversions.asString(changes.get("label")));
        }
        Set<ConstraintViolation<TagRequest>> violations = validator.validate(toRequest(item));
        if (!violations.isEmpty()) {
            throw new ConstraintViolationException(violations);
        }
        return toResponse(repository.update(item));
    }

    @Override
    public void delete(Long id) {
        if (!repository.existsById(id)) {
            throw new ResourceNotFoundException("Tag " + id + " not found");
        }
        repository.deleteById(id);
    }

    private Tag find(Long id) {
        return repository.findById(id).orElseThrow(() -> new ResourceNotFoundException("Tag " + id + " not found"));
    }

    /** The request's values onto the domain model (the key is the creation's business, see create). */
    private static void apply(TagRequest request, Tag item) {
        item.setLabel(request.label());
    }

    private static TagResponse toResponse(Tag item) {
        return new TagResponse(
                item.getId(),
                item.getLabel()
        );
    }

    private static TagRequest toRequest(Tag item) {
        return new TagRequest(
                item.getLabel()
        );
    }
}
