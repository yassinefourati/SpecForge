package com.example.api.security;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.http.HttpMethod;
import org.springframework.security.config.annotation.web.builders.HttpSecurity;
import org.springframework.security.config.annotation.web.configuration.EnableWebSecurity;
import org.springframework.security.config.http.SessionCreationPolicy;
import org.springframework.security.oauth2.server.resource.authentication.JwtAuthenticationConverter;
import org.springframework.security.oauth2.server.resource.authentication.JwtGrantedAuthoritiesConverter;
import org.springframework.security.web.SecurityFilterChain;
import org.springframework.security.web.access.expression.WebExpressionAuthorizationManager;
import org.springframework.security.web.authentication.UsernamePasswordAuthenticationFilter;

/**
 * Spring Security configuration generated from the security schemes of "Pet Store".
 *
 * Declared schemes:
 *  - apiKey: APIKEY (X-API-KEY in header)
 *  - oauth: OAUTH2 (flows: clientCredentials, token URL: https://auth.example.com/token)
 *
 * Access rules style: MATCHERS. Scope authorities use the prefix "SCOPE_".
 *
 * Generated by SpecForge from "Pet Store" (1.0.0). Safe to edit.
 */
@Configuration
@EnableWebSecurity
public class SecurityConfig {

    @Bean
    public SecurityFilterChain securityFilterChain(HttpSecurity http,
            @Value("${app.security.api-keys:}") String apiKeys) throws Exception {
        http
            .csrf(csrf -> csrf.disable())
            .sessionManagement(session -> session.sessionCreationPolicy(SessionCreationPolicy.STATELESS))
            .authorizeHttpRequests(auth -> {
                // one statement per rule: a single chained expression overflows javac's stack on large APIs
                auth.requestMatchers(HttpMethod.GET, "/v1/pets").permitAll();
                auth.requestMatchers(HttpMethod.POST, "/v1/pets").authenticated();
                auth.requestMatchers(HttpMethod.GET, "/v1/pets/{petId}").permitAll();
                auth.requestMatchers(HttpMethod.DELETE, "/v1/pets/{petId}").access(new WebExpressionAuthorizationManager("hasAuthority('SCOPE_write:pets')"));
                auth.anyRequest().authenticated();
            });
        http.oauth2ResourceServer(oauth2 -> oauth2.jwt(jwt -> jwt.jwtAuthenticationConverter(jwtAuthenticationConverter())));
        http.addFilterBefore(new ApiKeyAuthFilter(apiKeys), UsernamePasswordAuthenticationFilter.class);
        return http.build();
    }

    /** Maps the token's scopes ("scope" / "scp" claims) to authorities such as SCOPE_read. */
    @Bean
    public JwtAuthenticationConverter jwtAuthenticationConverter() {
        JwtGrantedAuthoritiesConverter scopes = new JwtGrantedAuthoritiesConverter();
        scopes.setAuthorityPrefix("SCOPE_");
        JwtAuthenticationConverter converter = new JwtAuthenticationConverter();
        converter.setJwtGrantedAuthoritiesConverter(scopes);
        return converter;
    }
}
