/**
 * The web layer of TagController: status codes, the page shape and validation, with the service mocked
 * (filters off: security is the application's, see SecurityConfig).
 *
 * Generated by SpecForge from "Shop" (1.0.0). Safe to edit.
 */
@WebMvcTest(TagController.class)
@AutoConfigureMockMvc(addFilters = false)
class TagControllerTest {

    @Autowired
    MockMvc mvc;

    @MockitoBean
    TagService service;

    @Test
    void listAnswersWithAPage() throws Exception {
        given(service.list(anyMap(), any())).willReturn(new PageResponse<>(List.of(), 0, 20, 0, 0));
        mvc.perform(get("/tags"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.totalElements").value(0));
    }

    @Test
    void anUnknownKeyIsNotFound() throws Exception {
        given(service.read(any())).willThrow(new ResourceNotFoundException("not found"));
        mvc.perform(get("/tags/1")).andExpect(status().isNotFound());
    }

    @Test
    void anIncompleteBodyIsRejected() throws Exception {
        mvc.perform(post("/tags").contentType(MediaType.APPLICATION_JSON).content("{}"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void deleteAnswersNoContent() throws Exception {
        mvc.perform(delete("/tags/1")).andExpect(status().isNoContent());
    }
}
