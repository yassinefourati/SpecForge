package com.admintemplate.shop;

import jakarta.validation.Valid;

import com.admintemplate.common.PageResponse;
import com.admintemplate.shop.CountryDtos.CountryRequest;
import com.admintemplate.shop.CountryDtos.CountryResponse;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import org.springframework.http.HttpStatus;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

/**
 * Countries: every signed-in user reads; changes need the permission "shop.manage".
 *
 * Generated by SpecForge from "Shop" (1.0.0). Safe to edit.
 */
// bean names carry the module: the project may have a CountryController of its own
@RestController("shopCountryController")
@RequestMapping("/api/shop/countries")
@Tag(name = "Countries")
public class CountryController {

    private final CountryService service;

    public CountryController(CountryService service) {
        this.service = service;
    }

    @GetMapping
    @Operation(summary = "One page of countries; q searches code, name")
    public PageResponse<CountryResponse> list(@RequestParam(required = false) String q,
            @RequestParam(required = false) String code,
            @RequestParam(required = false) String name,
            @RequestParam(defaultValue = "0") int page, @RequestParam(defaultValue = "20") int size,
            @RequestParam(required = false) String sort) {
        return service.list(q, code, name, page, size, sort);
    }

    @GetMapping("/{id}")
    public CountryResponse get(@PathVariable String id) {
        return service.get(id);
    }

    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    @PreAuthorize("hasAuthority('shop.manage')")
    public CountryResponse create(@Valid @RequestBody CountryRequest request) {
        return service.create(request);
    }

    @PutMapping("/{id}")
    @PreAuthorize("hasAuthority('shop.manage')")
    public CountryResponse update(@PathVariable String id, @Valid @RequestBody CountryRequest request) {
        return service.update(id, request);
    }

    @DeleteMapping("/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    @PreAuthorize("hasAuthority('shop.manage')")
    public void delete(@PathVariable String id) {
        service.delete(id);
    }
}
