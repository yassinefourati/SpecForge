package com.admintemplate.shop;

import jakarta.validation.Valid;

import com.admintemplate.common.PageResponse;
import com.admintemplate.shop.TagDtos.TagRequest;
import com.admintemplate.shop.TagDtos.TagResponse;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.tags.Tag;
import org.springframework.http.HttpStatus;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.PutMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;

/**
 * Tags: every signed-in user reads; changes need the permission "shop.manage".
 *
 * Generated by SpecForge from "Shop" (1.0.0). Safe to edit.
 */
// bean names carry the module: the project may have a TagController of its own
@RestController("shopTagController")
@RequestMapping("/api/shop/tags")
@Tag(name = "Tags")
public class TagController {

    private final TagService service;

    public TagController(TagService service) {
        this.service = service;
    }

    @GetMapping
    @Operation(summary = "One page of tags; q searches label")
    public PageResponse<TagResponse> list(@RequestParam(required = false) String q,
            @RequestParam(required = false) Long id,
            @RequestParam(required = false) String label,
            @RequestParam(defaultValue = "0") int page, @RequestParam(defaultValue = "20") int size,
            @RequestParam(required = false) String sort) {
        return service.list(q, id, label, page, size, sort);
    }

    @GetMapping("/{id}")
    public TagResponse get(@PathVariable Long id) {
        return service.get(id);
    }

    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    @PreAuthorize("hasAuthority('shop.manage')")
    public TagResponse create(@Valid @RequestBody TagRequest request) {
        return service.create(request);
    }

    @PutMapping("/{id}")
    @PreAuthorize("hasAuthority('shop.manage')")
    public TagResponse update(@PathVariable Long id, @Valid @RequestBody TagRequest request) {
        return service.update(id, request);
    }

    @DeleteMapping("/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    @PreAuthorize("hasAuthority('shop.manage')")
    public void delete(@PathVariable Long id) {
        service.delete(id);
    }
}
