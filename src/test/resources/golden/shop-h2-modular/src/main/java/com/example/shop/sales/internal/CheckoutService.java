@Service
@Transactional
public class CheckoutService {

    private final OrderService orderService;

    private final OrderItemService orderItemService;

    private final CustomerService customerService;
    private final OrderItemMapper orderItemMapper;
    private final OrderItemRepository orderItemRepository;
    private final OrderRepository orderRepository;

    public CheckoutService(OrderService orderService, OrderItemService orderItemService, CustomerService customerService, OrderItemMapper orderItemMapper, OrderItemRepository orderItemRepository, OrderRepository orderRepository) {
        this.orderService = orderService;
        this.orderItemService = orderItemService;
        this.customerService = customerService;
        this.orderItemMapper = orderItemMapper;
        this.orderItemRepository = orderItemRepository;
        this.orderRepository = orderRepository;
    }

    public OrderWithOrderItems createOrderWithOrderItems(OrderWithOrderItemsRequest request) {
        OrderResponse order = orderService.create(request.order());
        List<OrderItemResponse> orderItems = new ArrayList<>();
        for (OrderItemInput item : request.orderItems()) {
            orderItems.add(orderItemService.create(new OrderItemRequest(order.id(), item.lineNo(), item.quantity(), item.productId())));
        }
        return new OrderWithOrderItems(order, orderItems);
    }

    public OrderWithOrderItems updateOrderWithOrderItems(Long id, OrderWithOrderItemsRequest request) {
        OrderResponse order = orderService.update(id, request.order());
        // the request carries the complete list: the old orderItems are replaced
        orderItemRepository.deleteAll(orderItemRepository.findAllByOrder_Id(id));
        orderItemRepository.flush();
        List<OrderItemResponse> orderItems = new ArrayList<>();
        for (OrderItemInput item : request.orderItems()) {
            orderItems.add(orderItemService.create(new OrderItemRequest(order.id(), item.lineNo(), item.quantity(), item.productId())));
        }
        return new OrderWithOrderItems(order, orderItems);
    }

    @Transactional(readOnly = true)
    public OrderWithOrderItems readOrderWithOrderItems(Long id) {
        OrderResponse order = orderService.read(id);
        List<OrderItemResponse> orderItems = orderItemRepository.findAllByOrder_Id(id).stream()
                .map(orderItemMapper::toDto).toList();
        return new OrderWithOrderItems(order, orderItems);
    }

    @Transactional(readOnly = true)
    public PageResponse<OrderItemResponse> listOrderItemsOfOrder(Long id, Pageable pageable) {
        if (!orderRepository.existsById(id)) {
            throw new ResourceNotFoundException("Order " + id + " not found");
        }
        return PageResponse.of(orderItemRepository.findAllByOrder_Id(id, OrderItemService.sorted(pageable))
                .map(orderItemMapper::toDto));
    }
}
