package com.example.api.controller;

import java.util.List;

import jakarta.validation.Valid;

import com.example.api.entity.Pet;
import com.example.api.service.PetService;
import org.springframework.http.ResponseEntity;
import org.springframework.validation.annotation.Validated;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RestController;

/**
 * REST endpoints of the "Pet" API group.
 *
 * Generated by SpecForge from "Pet Store" (1.0.0). Safe to edit.
 */
@RestController
@RequestMapping("/v1")
@Validated
public class PetController {

    private final PetService petService;

    public PetController(PetService petService) {
        this.petService = petService;
    }

    /**
     * <p>GET /v1/pets
     * <p>Response 200: All pets
     */
    @GetMapping(value = "/pets", produces = "application/json")
    public ResponseEntity<List<Pet>> listPets() {
        return ResponseEntity.status(200).body(petService.listPets());
    }

    /**
     * <p>POST /v1/pets
     * <p>Response 201: Created
     *
     * @param body body (required)
     */
    @PostMapping(value = "/pets", consumes = "application/json", produces = "application/json")
    public ResponseEntity<Pet> addPet(
            @Valid @RequestBody Pet body) {
        return ResponseEntity.status(201).body(petService.addPet(body));
    }

    /**
     * <p>GET /v1/pets/{petId}
     * <p>Response 200: The pet
     *
     * @param petId path (required)
     */
    @GetMapping(value = "/pets/{petId}", produces = "application/json")
    public ResponseEntity<Pet> getPet(
            @PathVariable("petId") Long petId) {
        return ResponseEntity.status(200).body(petService.getPet(petId));
    }

    /**
     * <p>DELETE /v1/pets/{petId}
     * <p>Response 204: Deleted
     *
     * @param petId path (required)
     */
    @DeleteMapping(value = "/pets/{petId}")
    public ResponseEntity<Void> deletePet(
            @PathVariable("petId") Long petId) {
        petService.deletePet(petId);
        return ResponseEntity.status(204).build();
    }
}
